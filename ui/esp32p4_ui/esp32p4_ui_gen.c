void esp32p4_ui_set_target(uint32_t target)
{
    esp32p4_ui_target = target;
}

uint32_t esp32p4_ui_get_target(void)
{
    return esp32p4_ui_target;
}

bool esp32p4_ui_check_target(uint32_t target)
{
    return (esp32p4_ui_target & target) ? true : false;
}

